// Browser check of the mempool page in live mode. Run: node test/mempool.e2e.js  (needs Playwright)
const { chromium } = require('playwright');
const { execFileSync } = require('child_process');
const fs = require('fs'); const os = require('os'); const path = require('path'); const http = require('http');
const express = require('express');
const { ECPairFactory } = require('ecpair');
const ts = require('../src/tapseal');
const { createRouter } = require('../src/router');
const { bitcoin, ecc } = ts; const ECPair = ECPairFactory(ecc); const NET = bitcoin.networks.bitcoin;
const FIX = path.join(__dirname, 'fixture.py');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tapseal-mp-')); const DB = path.join(tmp, 'tapseal.sqlite');
const SK = Buffer.from('1f'.repeat(32), 'hex'); const user = ECPair.fromPrivateKey(SK, { network: NET });
const xOnly = user.publicKey.subarray(1);
const address = bitcoin.payments.p2tr({ internalPubkey: xOnly, network: NET }).address;
const tweaked = user.tweak(bitcoin.crypto.taggedHash('TapTweak', xOnly));
const py = (...a) => JSON.parse(execFileSync('python3', ['-I', FIX, ...a], { encoding: 'utf8' }));
(async () => {
  py('make', DB, SK.toString('hex'));
  const rpc = http.createServer((req, res) => { let b = ''; req.on('data', (c) => (b += c)); req.on('end', () => { const j = JSON.parse(b);
    res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({ result: bitcoin.Transaction.fromHex(j.params[0]).getId(), error: null, id: j.id })); }); });
  await new Promise((r) => rpc.listen(0, r));
  const app = express(); app.use(express.json());
  app.use('/api/tapseal', createRouter({ dbPath: DB, network: 'mainnet', mempoolApi: 'http://127.0.0.1:9', minServerUtxo: 10000, publicLaunch: true, ownerAddresses: [], featured: 'STONK', platformFee: { sats: 0 }, rpc: { url: `http://127.0.0.1:${rpc.address().port}` } }));
  app.use('/mempool', express.static(path.resolve(__dirname, '../../mempool')));
  const server = app.listen(0); await new Promise((r) => server.once('listening', r));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (p, body) => fetch(base + '/api/tapseal' + p, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }).then((r) => r.json());
  const built = await post('/psbt/mint', { tick: 'STONK', address, public_key: user.publicKey.toString('hex'), pay_sats: 30000, fee_rate: 7, utxos: [{ txid: 'ab'.repeat(32), vout: 0, value: 400000 }] });
  const psbt = bitcoin.Psbt.fromHex(built.psbt_hex, { network: NET }); built.sign_inputs.forEach((i) => psbt.signInput(i.index, tweaked)); psbt.finalizeAllInputs();
  const bc = await post('/broadcast', { psbt: psbt.toHex(), fee_sats: built.fee_sats });
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await b.newPage({ viewport: { width: 1440, height: 1000 } }); const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(`${base}/mempool/index.html`); await page.waitForTimeout(1500);
  const ok = (c, m) => { if (!c) throw new Error(m); console.log('ok  ', m); };
  ok(await page.textContent('#modePill') === 'Live', 'mempool page switches to live');
  ok((await page.textContent('#feed')).includes('STONK, 30,000 sats'), 'broadcast mint appears in the live feed with its payment');
  ok((await page.textContent('#press')).includes('1 pending mint'), 'mint pressure counts it against remaining supply');
  ok((await page.$$eval('.cube[data-kind="mined"]', (c) => c.length)) === 4, 'mined lane shows indexed blocks');
  await page.screenshot({ path: path.join(process.argv[2] || tmp, 'mempool-live.png') });
  const tx = psbt.extractTransaction(); const f = path.join(tmp, 'tx.json');
  fs.writeFileSync(f, JSON.stringify({ txid: tx.getId(), vin: tx.ins.map((i) => ({ prevout: `${Buffer.from(i.hash).reverse().toString('hex')}:${i.index}`, witness: i.witness.map((w) => w.toString('hex')) })), vout: tx.outs.map((o) => ({ value: o.value, spk: o.script.toString('hex') })) }));
  py('confirm', DB, f);
  await page.waitForFunction(() => document.querySelector('#gTip').textContent === '104' && !document.querySelector('#feed').textContent.includes('STONK, 30,000 sats'), null, { timeout: 15000 });
  ok(!(await page.textContent('#feed')).includes('STONK, 30,000 sats'), 'after the block, the op leaves the mempool feed');
  ok((await page.$$eval('.cube[data-kind="mined"]', (c) => c.map((x) => x.textContent).join(' '))).includes('1 TAPSEAL ops'), 'and shows up in the new mined block');
  console.log(errors.length ? `page errors: ${errors.join(' | ')}` : 'no page errors', bc.txid.slice(0, 8));
  await b.close(); server.close(); rpc.close();
})().catch((e) => { console.error('FAIL', e.message); process.exit(1); });
